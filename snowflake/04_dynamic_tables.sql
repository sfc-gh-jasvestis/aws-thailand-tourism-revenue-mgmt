-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT prop.ID AS ENTITY_ID, prop.NAME AS ENTITY_NAME,
       prop.REGION, prop.CATEGORY, prop.SERVICE_TIER, prop.STATUS,
       prop.AVAILABLE_ROOMS, prop.BUDGET_BOOKINGS_90D,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.BOOKING_COUNT) AS BOOKING_COUNT,
       SUM(observation.AT_RATE_COUNT) AS AT_RATE_COUNT,
       SUM(observation.PARITY_ALERT_COUNT) AS PARITY_ALERT_COUNT,
       SUM(observation.BREACH_COUNT) AS BREACH_COUNT,
       SUM(observation.CASE_OPENED) AS CASE_COUNT,
       SUM(observation.AUDIT_DUE) AS AUDIT_DUE,
       SUM(observation.AUDIT_COMPLETED) AS AUDIT_COMPLETED,
       SUM(observation.OCCUPIED_ROOMS) AS OCCUPIED_ROOM_NIGHTS,
       SUM(observation.AVAILABLE_ROOMS) AS AVAILABLE_ROOM_NIGHTS,
       SUM(observation.ROOM_REVENUE_THB) AS ROOM_REVENUE_THB,
       SUM(observation.ROOM_REVENUE_THB) / NULLIF(SUM(observation.OCCUPIED_ROOMS), 0) AS ADR_THB,
       SUM(observation.ROOM_REVENUE_THB) / NULLIF(SUM(observation.AVAILABLE_ROOMS), 0) AS REVPAR_THB,
       100.0 * SUM(observation.OCCUPIED_ROOMS) / NULLIF(SUM(observation.AVAILABLE_ROOMS), 0) AS OCCUPANCY_PCT,
       100.0 * SUM(observation.BOOKING_COUNT) / NULLIF(prop.BUDGET_BOOKINGS_90D, 0) AS BOOKINGS_VS_BUDGET_PCT,
       100.0 * (SUM(observation.BOOKING_COUNT) - SUM(observation.AT_RATE_COUNT)) / NULLIF(SUM(observation.BOOKING_COUNT), 0) AS BELOW_FLOOR_PCT,
       100.0 * SUM(observation.BREACH_COUNT) / NULLIF(SUM(observation.PARITY_ALERT_COUNT), 0) AS ALERT_CONFIRM_PCT,
       100.0 * SUM(observation.AUDIT_COMPLETED) / NULLIF(SUM(observation.AUDIT_DUE), 0) AS AUDIT_COMPLIANCE_PCT,
       AVG(observation.SYNC_LAG_HOURS) AS AVG_SYNC_LAG_HOURS,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.PROPERTY_DAILY observation
JOIN RAW.PROPERTIES prop ON prop.ID = observation.ENTITY_ID
GROUP BY prop.ID, prop.NAME, prop.REGION, prop.CATEGORY, prop.SERVICE_TIER, prop.STATUS,
         prop.AVAILABLE_ROOMS, prop.BUDGET_BOOKINGS_90D;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(BOOKING_COUNT) AS BOOKING_COUNT, SUM(AT_RATE_COUNT) AS AT_RATE_COUNT,
       SUM(PARITY_ALERT_COUNT) AS PARITY_ALERT_COUNT, SUM(BREACH_COUNT) AS BREACH_COUNT, SUM(ROOM_REVENUE_THB) AS ROOM_REVENUE_THB,
       100.0 * SUM(OCCUPIED_ROOMS) / NULLIF(SUM(AVAILABLE_ROOMS), 0) AS OCCUPANCY_PCT,
       SUM(ROOM_REVENUE_THB) / NULLIF(SUM(AVAILABLE_ROOMS), 0) AS REVPAR_THB,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(PARITY_ALERT_COUNT), 0) AS ALERT_CONFIRM_PCT
FROM RAW.PROPERTY_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.DRIVER_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT BREACH_DRIVER, SUM(PARITY_ALERT_COUNT) AS PARITY_ALERT_COUNT,
       SUM(BREACH_COUNT) AS BREACH_COUNT,
       SUM(CASE_OPENED) AS CASE_COUNT,
       COUNT(DISTINCT ENTITY_ID) AS PROPERTIES_AFFECTED,
       100.0 * SUM(BREACH_COUNT) / NULLIF(SUM(PARITY_ALERT_COUNT), 0) AS ALERT_CONFIRM_PCT
FROM RAW.PROPERTY_DAILY
WHERE PARITY_ALERT_COUNT > 0
GROUP BY BREACH_DRIVER;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PARITY_ALERT_COUNT) AS SIGNALS, SUM(BREACH_COUNT) AS CONFIRMED,
         SUM(CASE_OPENED) AS CASES, SUM(BOOKING_COUNT) AS BOOKED, SUM(AT_RATE_COUNT) AS AT_RATE,
         SUM(OCCUPIED_ROOMS) AS OCCUPIED, SUM(AVAILABLE_ROOMS) AS AVAILABLE,
         SUM(ROOM_REVENUE_THB) AS REVENUE,
         AVG(SYNC_LAG_HOURS) AS AVG_SYNC_LAG, SUM(OPEN_MISMATCHES) AS MISMATCH_TOTAL,
         SUM(AUDIT_DUE) AS AUDIT_DUE, SUM(AUDIT_COMPLETED) AS AUDIT_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.PROPERTY_DAILY
), portfolio AS (
  SELECT COUNT(*) AS PROPERTY_COUNT, SUM(BUDGET_BOOKINGS_90D) AS BUDGET, SUM(AVAILABLE_ROOMS) AS ROOMS
  FROM RAW.PROPERTIES
), channels AS (
  SELECT 100.0 * SUM(CHANNELS_AUDITED) / NULLIF(SUM(CHANNELS_CONNECTED), 0) AS COVERAGE_PCT,
         SUM(AUDITS_PENDING) AS PENDING
  FROM RAW.CHANNEL_CONNECTIONS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Bookings vs Budget' AS TITLE,
         100.0 * BOOKED / NULLIF(BUDGET, 0) AS VALUE_NUM, '%' AS UNIT FROM observations CROSS JOIN portfolio
  UNION ALL SELECT 2, 'Bookings', BOOKED, '' FROM observations
  UNION ALL SELECT 3, 'Room Occupancy', 100.0 * OCCUPIED / NULLIF(AVAILABLE, 0), '%' FROM observations
  UNION ALL SELECT 4, 'Average Daily Rate', REVENUE / NULLIF(OCCUPIED, 0), ' THB' FROM observations
  UNION ALL SELECT 5, 'RevPAR', REVENUE / NULLIF(AVAILABLE, 0), ' THB' FROM observations
  UNION ALL SELECT 6, 'Room Revenue', REVENUE / 1e6, ' M THB' FROM observations
  UNION ALL SELECT 7, 'Bookings Below Rate Floor', 100.0 * (BOOKED - AT_RATE) / NULLIF(BOOKED, 0), '%' FROM observations
  UNION ALL SELECT 8, 'Alert Confirmation Rate', 100.0 * CONFIRMED / NULLIF(SIGNALS, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Rate Parity Alerts', SIGNALS, '' FROM observations
  UNION ALL SELECT 10, 'Confirmed Parity Breaches', CONFIRMED, '' FROM observations
  UNION ALL SELECT 11, 'Channel Cases Opened', CASES, '' FROM observations
  UNION ALL SELECT 12, 'Rate-Loading Audit Compliance', 100.0 * AUDIT_COMPLETED / NULLIF(AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 13, 'Properties Active', PROPERTY_COUNT, '' FROM portfolio
  UNION ALL SELECT 14, 'Available Rooms', ROOMS, '' FROM portfolio
  UNION ALL SELECT 15, 'Channel Parity Audit Coverage', COVERAGE_PCT, '%' FROM channels
  UNION ALL SELECT 16, 'Channel Audits Pending', PENDING, '' FROM channels
  UNION ALL SELECT 17, 'Average Rate Sync Lag', AVG_SYNC_LAG, ' h' FROM observations
  UNION ALL SELECT 18, 'Open Rate Mismatches (property-day total)', MISMATCH_TOTAL, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT IN ('', ' THB') THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.DRIVER_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
